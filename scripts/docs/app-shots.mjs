const append = (rel, text) => (dir, fs, path) => fs.appendFileSync(path.join(dir, rel), text);
/** Replaces `from` (must occur) in a project file. */
const replace = (rel, from, to) => (dir, fs, path) => {
  const file = path.join(dir, rel);
  const s = fs.readFileSync(file, 'utf8');
  if (!s.includes(from)) throw new Error(`${rel}: "${from}" not found`);
  fs.writeFileSync(file, s.replace(from, to));
};

