/** Editor context, sidebar tab, view and selection: ctx({canvas, target, lang, sidebarTab, view, selection}). */
const ctx = (c) => `
  const store = await ui.store();
  const editor = await ui.editor();
  const c = ${JSON.stringify(c)};
  const patch = {};
  for (const k of ['canvas', 'target', 'lang']) if (c[k]) patch[k] = c[k];
  if (Object.keys(patch).length) await editor.setContext(patch);
  const rest = {};
  for (const k of ['sidebarTab', 'view', 'selection']) if (c[k] !== undefined) rest[k] = c[k];
  store.set(rest);
  await ui.idle();`;

/** Calls an exported function of an app module: open('dialogs/export', 'openExport'). */
const open = (mod, fn, ...args) => `(await ui.mod('${mod}')).${fn}(...${JSON.stringify(args)}); await ui.waitFor('.dlg[open]'); await ui.idle();`;
const projectSettings = (tab) => open('dialogs/project-settings', 'openProjectSettings', tab);
/** Scrolls the open dialog so the element with `text` is `offset` px below the top. */
const scrollTo = (sel, text, offset = 0) =>
  `const el = await ui.waitFor('.dlg[open] ${sel}', { text: ${JSON.stringify(text)} });
   el.scrollIntoView({ block: 'start' });
   el.closest('.dlg-body').scrollTop -= ${offset};
   await ui.sleep(200);`;
/** Zooms the canvas view: `ticks` ctrl+wheel steps (×1.28 each) around the element `sel`. */
const zoom = (sel, ticks, at = [0.5, 0.5]) => ({ wheel: sel, at, deltaY: -50, ctrl: true, times: ticks });
/** Pans the centre view by (dx, dy) CSS px (content moves left/up for positive values). */
const pan = (dx, dy) => ({ wheel: '#view', deltaX: dx, deltaY: dy });

