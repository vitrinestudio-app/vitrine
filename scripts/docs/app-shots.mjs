// Shot list of scripts/docs/app-screenshots.mjs (website app screenshots).
// How to run it and add shots: website/README.md, "Screenshots".
//
// `projects`: the sample projects, created by `app-screenshots.mjs init`
// from gallery templates in <root>/Projects/<name>.
//   template  gallery template id (`vitrine gallery list`)
//   langs     project languages (`vitrine new --lang …`)
//   files     files written into the project after `vitrine new` (null = delete)
//   edit      functions (dir, fs, path) run after that, e.g. append/replace
//
// `shots`: one entry per image pair `<name>.jpg` + `<name>-dark.jpg`, run in
// list order (keep shots of one project together: switching reopens it).
//   name      output file name without `.jpg`
//   project   key in `projects` (omitted = no project, start screen)
//   note      one line for `app-screenshots.mjs list`
//   query     extra URL parameters (`lang=en` and `theme` are set)
//   steps     run in order after the page has loaded:
//             - a string: an async function body run in the page, with
//               `ui` (helpers: mod, store, editor, waitFor, click, idle,
//               sleep – PAGE_HELPERS in app-screenshots.mjs) and `arg`
//               ({root, rootReal, theme});
//             - {cmd, args}: a dev bridge command from Node;
//             - {click|rightClick|dblClick|hover: selector, text?, at?: [fx, fy]}:
//               real mouse input at that element (fractions of its box);
//             - {wheel: selector, at?, deltaX?, deltaY?, ctrl?, times?}:
//               mouse wheel (ctrl = zoom), see zoom() / pan() below;
//             - {key: 'Escape'}; {wait: ms}
//   after     steps run after the capture, also on failure – undo project
//             changes made by `steps` ({cmd: 'undo'})
//   hide      selectors set to display: none before the capture
//   clip      'window' (default), a CSS selector of the element to crop to,
//             {selector, text?, pad?, width?, height?, maxHeight?},
//             {x, y, width, height} in CSS px, or {script: 'return {x, y, width, height}'}
//   maxWidth  cap of the image width in px (default 1520: dialogs; use 2400
//             for the full window) – the capture is scaled down to it
//   wait      extra ms before the capture (default 400)

